const plural = new Intl.PluralRules('ar');

/** Arabic has six plural categories; counts are written with Latin digits (see ADR 0004). */
function accountsCount(count: number): string {
  switch (plural.select(count)) {
    case 'zero':
      return 'لا توجد حسابات';
    case 'one':
      return 'حساب واحد';
    case 'two':
      return 'حسابان';
    case 'few':
      return `${count} حسابات`;
    case 'many':
      return `${count} حسابًا`;
    case 'other':
      return `${count} حساب`;
  }
}

